def seed() -> None:
    with SessionLocal() as db:
        numbers: dict[str, ExamNumber] = {}
        for position, (code, title) in enumerate(EXAM_NUMBERS, start=1):
            number = db.scalar(select(ExamNumber).where(ExamNumber.code == code))
            if number is None:
                number = ExamNumber(code=code, title=title, position=position)
                db.add(number)
            numbers[code] = number
        db.flush()

        added = 0
        for item in TASKS:
            data = dict(item)
            number = numbers[data.pop("exam_number")]
            exists = db.scalar(select(Task.id).where(Task.statement == data["statement"]))
            if exists is None:
                db.add(Task(**data, exam_number=number))
                added += 1

        for item in GAME_TASKS:
            data = dict(item)
            number = numbers[data.pop("exam_number")]
            parts = [
                TaskPart(number=n, question=q, correct_answer=a, explanation=e)
                for n, q, a, e in data.pop("parts")
            ]
            exists = db.scalar(select(Task.id).where(Task.statement == data["statement"]))
            if exists is None:
                summary = "; ".join(f"{p.number}: {p.correct_answer}" for p in parts)
                db.add(Task(**data, correct_answer=summary, exam_number=number, parts=parts))
                added += 1

        db.commit()
        seed_catalog(db)
        print(f"Номеров ЕГЭ: {len(numbers)}, добавлено задач: {added}")


if __name__ == "__main__":
    seed()
